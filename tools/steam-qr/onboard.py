#!/usr/bin/env python3
"""Offline-only prototype for a verified, opted-in Friends ASF bot.

The QR is generated by Steam over the steam-session SteamClient transport.
Only the exact SteamID/login previously verified on the Friends website may
be imported. Credentials never pass through Friends HTTP or container logs.
"""
import argparse
import base64
import json
import os
import re
import sqlite3
import tempfile
import time
from pathlib import Path

STEAM_ID = re.compile(r"7656119[0-9]{10}$")
BOT_NAME = re.compile(r"fh_account_[0-9]+$")


def context(friends_db, config_dir, account_id):
    if account_id < 1:
        raise ValueError("Invalid Steam account ID")
    with sqlite3.connect(Path(friends_db).resolve().as_uri() + "?mode=ro", uri=True) as db:
        row = db.execute("""
            SELECT a.id,a.steam_id,a.login,a.requested,u.disabled
            FROM steam_accounts a JOIN users u ON u.id=a.user_id
            WHERE a.id=?
        """, (account_id,)).fetchone()
    if not row or not row[3] or row[4]:
        raise ValueError("Account is not verified and opted in, or owner is disabled")
    _, steam_id, login, _, _ = row
    if not STEAM_ID.fullmatch(str(steam_id)) or not re.fullmatch(r"[A-Za-z0-9_]{3,64}", login or ""):
        raise ValueError("Missing a valid SteamID and login name")
    config_dir = Path(config_dir).resolve()
    name = f"fh_account_{account_id}"
    if not BOT_NAME.fullmatch(name):
        raise ValueError("Unexpected bot name")
    cfg = config_dir / f"{name}.json"
    if not cfg.is_file() or cfg.is_symlink():
        raise ValueError("Run the normal ASF provisioner first")
    settings = json.loads(cfg.read_text())
    if settings.get("Enabled") is not False or settings.get("SteamLogin") != login:
        raise ValueError("Bot is active or config login does not match the request")
    database = config_dir / f"{name}.db"
    if database.is_symlink():
        raise ValueError("Refusing linked bot database")
    if database.exists():
        if database.stat().st_size > 4_000_000:
            raise ValueError("Unexpectedly large bot database")
        old = json.loads(database.read_text())
        if old.get("BackingRefreshToken"):
            raise ValueError("Existing authorized session: use the separate reauthentication procedure")
    return name, steam_id, login, cfg, database


def validate_refresh_token(token, steam_id):
    if not isinstance(token, str) or len(token) > 16_384 or len(token) < 80:
        raise ValueError("Invalid Steam token length")
    segments = token.split(".")
    if len(segments) != 3:
        raise ValueError("Invalid Steam token shape")
    try:
        payload = json.loads(base64.urlsafe_b64decode(segments[1] + "=" * (-len(segments[1]) % 4)))
    except (ValueError, UnicodeDecodeError) as e:
        raise ValueError("Invalid Steam token claims") from e
    audience = payload.get("aud", [])
    audience = [audience] if isinstance(audience, str) else audience
    if payload.get("sub") != steam_id or "client" not in audience:
        raise ValueError("Token belongs to a different SteamID or is not SteamClient")
    if not isinstance(payload.get("exp"), (int, float)) or payload["exp"] < time.time() + 900:
        raise ValueError("Token is expired")
    # Parsing a JWT is NOT signature verification. The only accepted input
    # comes from our private 0700 temp directory written by steam-session's
    # authenticated SteamClient session after its independent SteamID check.
    return True


def atomic_json(path, value):
    fd, temporary = tempfile.mkstemp(prefix=".fh-qr-", dir=path.parent)
    try:
        with os.fdopen(fd, "w") as output:
            json.dump(value, output, indent=2)
            output.write("\n")
        os.chmod(temporary, 0o600)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def import_session(token, steam_id, cfg_path, db_path):
    validate_refresh_token(token, steam_id)
    settings = json.loads(cfg_path.read_text())
    if settings.get("Enabled") is not False:
        raise ValueError("The bot must be disabled before importing a session")
    database = json.loads(db_path.read_text()) if db_path.exists() else {}
    if database.get("BackingRefreshToken"):
        raise ValueError("Existing authorized session; refusing overwrite")
    # Persistent SteamClient session is the backing property ASF loads.
    database["BackingRefreshToken"] = token
    atomic_json(db_path, database)
    # The explicit separate activation step is necessary after offline ASF
    # login verification. Never auto-enable by writing an untested token.
    return db_path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--friends-db", required=True)
    parser.add_argument("--asf-config", required=True)
    parser.add_argument("--account-id", type=int, required=True)
    parser.add_argument("--node", default="node")
    parser.add_argument("--apply", action="store_true", help="Start one live Steam QR login and import verified session")
    args = parser.parse_args()
    name, steam_id, login, cfg, botdb = context(args.friends_db, args.asf_config, args.account_id)
    print(f"Bot: {name}; verified SteamID {steam_id}; login name {login}")
    if not args.apply:
        print("Dry run only: use --apply when the Steam account owner can approve a QR code.")
        return
    raise SystemExit("Live QR authentication is intentionally disabled pending verified ASF import, identity attestation and revocation.")


if __name__ == "__main__":
    main()
